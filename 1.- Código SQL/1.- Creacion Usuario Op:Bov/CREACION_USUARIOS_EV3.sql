-- CREACION DE USUARIO DE BASE DE DATOS OPERACIONAL 
--==============================================================================
DROP USER ADMIN_FIT_OP CASCADE;
CREATE USER ADMIN_FIT_OP
IDENTIFIED BY ADMIN_FIT_OP

DEFAULT TABLESPACE USERS 
TEMPORARY TABLESPACE TEMP;
ALTER USER ADMIN_FIT_OP QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION TO ADMIN_FIT_OP;
GRANT "RESOURCE" TO ADMIN_FIT_OP;
ALTER USER ADMIN_FIT_OP DEFAULT ROLE "RESOURCE";

--==============================================================================

-- CREACION DE USUARIO DE BASE DE DATOS BOVEDA
--==============================================================================

DROP USER ADMIN_FIT_BOV CASCADE;
CREATE USER ADMIN_FIT_BOV 
IDENTIFIED BY ADMIN_FIT_BOV

DEFAULT TABLESPACE USERS
TEMPORARY TABLESPACE TEMP;
ALTER USER ADMIN_FIT_BOV QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION TO ADMIN_FIT_BOV;
GRANT "RESOURCE" TO ADMIN_FIT_BOV;
ALTER USER ADMIN_FIT_BOV DEFAULT ROLE "RESOURCE";

