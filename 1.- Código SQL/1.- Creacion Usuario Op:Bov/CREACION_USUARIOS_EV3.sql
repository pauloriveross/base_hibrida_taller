GRANT CREATE PROCEDURE TO ADMIN_FIT_BOV;
GRANT EXECUTE ON SYS.DBMS_CRYPTO TO ADMIN_FIT_BOV;
GRANT EXECUTE ON SYS.UTL_RAW TO ADMIN_FIT_BOV;
GRANT EXECUTE ON SYS.UTL_I18N TO ADMIN_FIT_BOV;

